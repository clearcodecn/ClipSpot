import AppKit
import SwiftUI
import Carbon.HIToolbox
import ApplicationServices
import CryptoKit
import UniformTypeIdentifiers

struct Clip: Codable, Identifiable {
    var id: String
    var text: String?
    var imageFile: String?
    var imageType: String?
    var lastUsed: Date
    var pasteCount: Int
}

final class ClipboardStore: ObservableObject {
    @Published var clips: [Clip] = []
    @Published var limit: Int = max(1, UserDefaults.standard.integer(forKey: "historyLimit") == 0 ? 99 : UserDefaults.standard.integer(forKey: "historyLimit"))
    private let dir: URL
    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let excludedTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    init() {
        dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("ClipSpot", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        if let data = try? Data(contentsOf: dir.appendingPathComponent("history.json")), let saved = try? JSONDecoder().decode([Clip].self, from: data) { clips = saved }
        trim()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }
    func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != changeCount else { return }
        changeCount = pb.changeCount
        guard let item = pb.pasteboardItems?.first, !item.types.contains(where: { excludedTypes.contains($0.rawValue) }) else { return }
        let text = item.string(forType: .string)
        let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff]
        let type = imageTypes.first { item.data(forType: $0) != nil }
        let image = type.flatMap { item.data(forType: $0) }
        guard (text?.isEmpty == false) || image != nil else { return }
        var hashInput = Data((text ?? "").utf8)
        hashInput.append(0)
        if let image { hashInput.append(image) }
        let id = SHA256.hash(data: hashInput).map { String(format: "%02x", $0) }.joined()
        if let index = clips.firstIndex(where: { $0.id == id }) {
            clips[index].lastUsed = Date()
        } else {
            var filename: String?
            if let image, let type {
                let name = id + (type == .png ? ".png" : ".tiff")
                do { try image.write(to: dir.appendingPathComponent(name), options: .atomic); filename = name }
                catch { NSLog("Unable to save clipboard image: %@", error.localizedDescription) }
            }
            guard text?.isEmpty == false || filename != nil else { return }
            clips.append(Clip(id: id, text: text, imageFile: filename, imageType: type?.rawValue, lastUsed: Date(), pasteCount: 0))
        }
        trim(); save()
    }
    func image(for clip: Clip) -> NSImage? { clip.imageFile.flatMap { NSImage(contentsOf: dir.appendingPathComponent($0)) } }
    func paste(_ clip: Clip) {
        let pb = NSPasteboard.general
        let item = NSPasteboardItem()
        if let text = clip.text { item.setString(text, forType: .string) }
        if let file = clip.imageFile, let type = clip.imageType, let data = try? Data(contentsOf: dir.appendingPathComponent(file)) { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
        pb.clearContents(); pb.writeObjects([item]); changeCount = pb.changeCount
        if let index = clips.firstIndex(where: { $0.id == clip.id }) { clips[index].pasteCount += 1; clips[index].lastUsed = Date(); trim(); save() }
    }
    func updateLimit(_ value: Int) { limit = max(1, min(9999, value)); UserDefaults.standard.set(limit, forKey: "historyLimit"); trim(); save() }
    func clear() { for clip in clips { removeImage(clip) }; clips.removeAll(); save() }
    private func removeImage(_ clip: Clip) { if let file = clip.imageFile { try? FileManager.default.removeItem(at: dir.appendingPathComponent(file)) } }
    private func trim() { clips.sort { $0.lastUsed > $1.lastUsed }; if clips.count > limit { clips.suffix(from: limit).forEach(removeImage); clips = Array(clips.prefix(limit)) } }
    private func save() { do { try JSONEncoder().encode(clips).write(to: dir.appendingPathComponent("history.json"), options: .atomic) } catch { NSLog("Unable to save clipboard history: %@", error.localizedDescription) } }
}

final class SearchModel: ObservableObject {
    @Published var query = ""
    @Published var selection = 0
    @Published var favorites = false
    let store: ClipboardStore
    init(store: ClipboardStore) { self.store = store }
    var results: [Clip] {
        let candidates = favorites ? Array(store.clips.filter { $0.pasteCount >= 3 }.prefix(99)) : store.clips
        return candidates.filter { query.isEmpty || ($0.text ?? "图片").localizedCaseInsensitiveContains(query) }
    }
}

struct SearchView: View {
    @ObservedObject var model: SearchModel
    @ObservedObject var store: ClipboardStore
    var choose: (Clip) -> Void
    var close: () -> Void
    @FocusState private var focused: Bool
    var body: some View {
        VStack(spacing: 0) {
            HStack(spacing: 12) {
                Image(systemName: "magnifyingglass").font(.system(size: 23)).foregroundStyle(.secondary)
                TextField("搜索剪贴板历史", text: $model.query).textFieldStyle(.plain).font(.system(size: 23)).focused($focused)
                Button(action: close) { Image(systemName: "xmark.circle.fill").font(.system(size: 18)).foregroundStyle(.secondary) }
                    .buttonStyle(.plain).help("关闭 (Esc)")
            }.padding(18)
            Divider()
            HStack {
                Button("最近", action: { model.favorites = false; model.selection = 0 }).buttonStyle(.plain).foregroundStyle(model.favorites ? .secondary : .primary)
                Button("常用", action: { model.favorites = true; model.selection = 0 }).buttonStyle(.plain).foregroundStyle(model.favorites ? .primary : .secondary)
                Spacer(); Text("↑↓ 选择   ↵ 粘贴   ⇥ 切换").font(.caption).foregroundStyle(.secondary)
            }.padding(.horizontal, 18).padding(.vertical, 9)
            if model.results.isEmpty { Text("暂无记录").foregroundStyle(.secondary).frame(maxWidth: .infinity, minHeight: 70) }
            else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(spacing: 2) {
                            ForEach(Array(model.results.enumerated()), id: \.element.id) { index, clip in
                                HStack(spacing: 12) {
                                    if let image = store.image(for: clip) { Image(nsImage: image).resizable().scaledToFit().frame(width: 42, height: 38).cornerRadius(4) }
                                    else { Image(systemName: "doc.text").font(.title3).frame(width: 42, height: 38).foregroundStyle(.secondary) }
                                    VStack(alignment: .leading, spacing: 3) {
                                        Text(clip.text?.replacingOccurrences(of: "\n", with: " ") ?? "图片").lineLimit(1)
                                        Text(clip.lastUsed, style: .relative).font(.caption).foregroundStyle(.secondary)
                                    }
                                    Spacer()
                                    if clip.pasteCount >= 3 { Image(systemName: "star.fill").foregroundStyle(.yellow).font(.caption) }
                                }.padding(.horizontal, 12).padding(.vertical, 6).background(index == model.selection ? Color.accentColor.opacity(0.23) : Color.clear).cornerRadius(7).contentShape(Rectangle()).onTapGesture { choose(clip) }.id(index)
                            }
                        }.padding(.horizontal, 8).padding(.bottom, 8)
                    }.frame(maxHeight: 360).onChange(of: model.selection) { index in withAnimation { proxy.scrollTo(index) } }
                }
            }
        }.frame(width: 620).background(.regularMaterial).onAppear { focused = true }.onChange(of: model.query) { _ in model.selection = 0 }
    }
}

final class SearchPanel: NSPanel {
    var handleKey: ((NSEvent) -> Bool)?
    var handleResignKey: (() -> Void)?
    override func resignKey() { super.resignKey(); handleResignKey?() }
    override var canBecomeKey: Bool { true }
    override var canBecomeMain: Bool { true }
    override func sendEvent(_ event: NSEvent) { if event.type == .keyDown, handleKey?(event) == true { return }; super.sendEvent(event) }
}

final class AppDelegate: NSObject, NSApplicationDelegate {
    let store = ClipboardStore()
    lazy var model = SearchModel(store: store)
    var panel: SearchPanel?
    var previousApp: NSRunningApplication?
    var status: NSStatusItem?
    var hotkey: EventHotKeyRef?
    var handler: EventHandlerRef?
    func applicationDidFinishLaunching(_ notification: Notification) {
        NSApp.setActivationPolicy(.accessory)
        status = NSStatusBar.system.statusItem(withLength: NSStatusItem.variableLength)
        status?.button?.image = NSImage(systemSymbolName: "clipboard", accessibilityDescription: "ClipSpot")
        let menu = NSMenu()
        menu.addItem(NSMenuItem(title: "打开剪贴板", action: #selector(showSearch), keyEquivalent: ""))
        menu.addItem(NSMenuItem(title: "清除历史…", action: #selector(confirmClear), keyEquivalent: ""))
        menu.addItem(NSMenuItem(title: "设置历史条数…", action: #selector(settings), keyEquivalent: ""))
        menu.addItem(NSMenuItem(title: "检查辅助功能权限…", action: #selector(requestPermission), keyEquivalent: ""))
        menu.addItem(.separator())
        menu.addItem(NSMenuItem(title: "退出 ClipSpot", action: #selector(quit), keyEquivalent: "q"))
        status?.menu = menu
        registerHotkey()
    }
    func registerHotkey() {
        var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
        let callback: EventHandlerUPP = { _, _, userData in
            guard let userData else { return noErr }
            DispatchQueue.main.async { Unmanaged<AppDelegate>.fromOpaque(userData).takeUnretainedValue().showSearch() }
            return noErr
        }
        InstallEventHandler(GetApplicationEventTarget(), callback, 1, &spec, Unmanaged.passUnretained(self).toOpaque(), &handler)
        let result = RegisterEventHotKey(UInt32(kVK_ANSI_V), UInt32(controlKey), EventHotKeyID(signature: 0x434C4950, id: 1), GetApplicationEventTarget(), 0, &hotkey)
        if result != noErr { let alert = NSAlert(); alert.messageText = "无法注册 Control + V"; alert.informativeText = "快捷键可能已被其他应用占用。你仍然可以从菜单栏打开剪贴板。"; alert.runModal() }
    }
    @objc func showSearch() {
        if panel?.isVisible == true { panel?.orderOut(nil); previousApp?.activate(); return }
        store.poll(); previousApp = NSWorkspace.shared.frontmostApplication
        model.query = ""; model.selection = 0; model.favorites = false
        let panel = SearchPanel(contentRect: NSRect(x: 0, y: 0, width: 620, height: 300), styleMask: [.titled, .fullSizeContentView, .nonactivatingPanel], backing: .buffered, defer: false)
        panel.titleVisibility = .hidden; panel.titlebarAppearsTransparent = true; panel.isMovableByWindowBackground = true
        panel.standardWindowButton(.closeButton)?.isHidden = true; panel.standardWindowButton(.miniaturizeButton)?.isHidden = true; panel.standardWindowButton(.zoomButton)?.isHidden = true
        panel.level = .floating; panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]; panel.isReleasedWhenClosed = false
        panel.contentView = NSHostingView(rootView: SearchView(model: model, store: store, choose: { [weak self] in self?.choose($0) }, close: { [weak self] in self?.closeSearch() }))
        panel.handleKey = { [weak self] event in self?.key(event) ?? false }
        panel.handleResignKey = { [weak panel] in panel?.orderOut(nil) }
        panel.center(); if let screen = NSScreen.main { var frame = panel.frame; frame.origin.y = screen.visibleFrame.midY + screen.visibleFrame.height * 0.1; panel.setFrame(frame, display: false) }
        self.panel = panel; NSApp.activate(ignoringOtherApps: true); panel.makeKeyAndOrderFront(nil)
    }
    func closeSearch() { panel?.orderOut(nil); previousApp?.activate() }
    func key(_ event: NSEvent) -> Bool {
        switch event.keyCode {
        case 53: closeSearch(); return true
        case 125: model.selection = min(model.selection + 1, max(0, model.results.count - 1)); return true
        case 126: model.selection = max(0, model.selection - 1); return true
        case 48: model.favorites.toggle(); model.selection = 0; return true
        case 36, 76: if model.results.indices.contains(model.selection) { choose(model.results[model.selection]) }; return true
        default: return false
        }
    }
    func choose(_ clip: Clip) {
        guard AXIsProcessTrusted() else {
            let alert = NSAlert(); alert.messageText = "需要辅助功能权限"; alert.informativeText = "请在辅助功能设置中允许 ClipSpot。若已经开启，请先移除旧的 ClipSpot 条目，再重新添加当前应用并开启。授权后重新选择记录。"; alert.addButton(withTitle: "打开设置"); alert.addButton(withTitle: "取消")
            if alert.runModal() == .alertFirstButtonReturn { requestPermission() }; return
        }
        store.paste(clip); panel?.orderOut(nil); previousApp?.activate()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.25) {
            guard let source = CGEventSource(stateID: .combinedSessionState), let down = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true), let up = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false) else { return }
            down.flags = .maskCommand; up.flags = .maskCommand; down.post(tap: .cghidEventTap); up.post(tap: .cghidEventTap)
        }
    }
    @objc func requestPermission() {
        // The search panel floats above other apps, so hide it before showing System Settings.
        panel?.orderOut(nil)
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") {
            NSWorkspace.shared.open(url)
        }
    }
    @objc func settings() {
        let alert = NSAlert(); alert.messageText = "历史记录条数"; alert.informativeText = "设置 1 到 9999 条，默认 99 条。"
        let field = NSTextField(string: String(store.limit)); field.frame = NSRect(x: 0, y: 0, width: 200, height: 24); alert.accessoryView = field
        alert.addButton(withTitle: "保存"); alert.addButton(withTitle: "取消"); NSApp.activate(ignoringOtherApps: true)
        if alert.runModal() == .alertFirstButtonReturn, let value = Int(field.stringValue), (1...9999).contains(value) { store.updateLimit(value) }
    }
    @objc func confirmClear() { let alert = NSAlert(); alert.messageText = "清除所有历史记录？"; alert.informativeText = "已保存的文本和图片会从本机删除。系统当前剪贴板不会被清除。"; alert.addButton(withTitle: "清除"); alert.addButton(withTitle: "取消"); NSApp.activate(ignoringOtherApps: true); if alert.runModal() == .alertFirstButtonReturn { store.clear() } }
    @objc func quit() { NSApp.terminate(nil) }
}
let app = NSApplication.shared
let delegate = AppDelegate()
app.delegate = delegate
app.run()
